#!/usr/bin/env node
// Splits assets-src/dictionaries/{ja,en}.json into one JSON file per owned
// namespace (spec §11) and generates src/i18n/dictionaries/index.ts.
//
//   node scripts/split-dictionaries.mjs           write the files
//   node scripts/split-dictionaries.mjs --check   fail if the split is stale
//
// After the initial split the per-namespace files are the source of truth
// (each package edits its own file). Re-running overwrites them from
// assets-src, so only do that deliberately.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'assets-src/dictionaries');
const OUT = join(ROOT, 'src/i18n/dictionaries');
const LOCALES = ['ja', 'en'];
const CHECK = process.argv.includes('--check');

/** Composition order of the Dictionary type. A dotted path becomes a nested object. */
const NAMESPACES = [
  'meta', 'common', 'a11y', 'header', 'stickyBar', 'qrDock', 'footer', 'personas',
  'home.hero', 'home.cast', 'home.about', 'home.call', 'home.demo', 'home.checkpoint',
  'home.morning', 'home.chat', 'home.live', 'home.grow',
  'home.more', 'home.how', 'home.faq', 'home.creatorsBand', 'home.final',
  'creators',
  'mock.fan', 'mock.studio',
];

const get = (obj, path) => path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);
const ident = (lang, ns) =>
  lang + ns.split('.').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

function flatKeys(obj, prefix = '') {
  return Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object' ? flatKeys(v, `${prefix}${k}.`) : [`${prefix}${k}`],
  );
}

let stale = 0;
function emit(file, content) {
  if (CHECK) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) {
      console.error(`stale: ${file.slice(ROOT.length + 1)}`);
      stale++;
    }
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}

for (const lang of LOCALES) {
  const dict = JSON.parse(readFileSync(join(SRC, `${lang}.json`), 'utf8'));
  // Every top-level key must be covered exactly once by NAMESPACES.
  const covered = new Set(NAMESPACES.map((ns) => ns.split('.')[0]));
  for (const top of Object.keys(dict)) {
    if (!covered.has(top)) throw new Error(`${lang}.json: top-level key "${top}" is not in NAMESPACES`);
  }
  for (const parent of ['home', 'mock']) {
    const listed = NAMESPACES.filter((ns) => ns.startsWith(`${parent}.`)).map((ns) => ns.split('.')[1]);
    for (const k of Object.keys(dict[parent])) {
      if (!listed.includes(k)) throw new Error(`${lang}.json: "${parent}.${k}" is not in NAMESPACES`);
    }
  }
  let total = 0;
  for (const ns of NAMESPACES) {
    const part = get(dict, ns);
    if (!part || typeof part !== 'object') throw new Error(`${lang}.json: missing namespace "${ns}"`);
    total += flatKeys(part).length;
    emit(join(OUT, lang, `${ns}.json`), JSON.stringify(part, null, 2) + '\n');
  }
  if (!CHECK) console.log(`${lang}: ${NAMESPACES.length} files, ${total} keys`);
}

/** Builds `{ meta: jaMeta, home: { hero: jaHomeHero, … }, … }` source text. */
function composition(lang, indent = '  ') {
  const tree = {};
  for (const ns of NAMESPACES) {
    const parts = ns.split('.');
    let node = tree;
    parts.slice(0, -1).forEach((p) => (node = node[p] ??= {}));
    node[parts.at(-1)] = ident(lang, ns);
  }
  const render = (node, pad) =>
    '{\n' +
    Object.entries(node)
      .map(([k, v]) => `${pad}${indent}${k}: ${typeof v === 'string' ? v : render(v, pad + indent)},`)
      .join('\n') +
    `\n${pad}}`;
  return render(tree, '');
}

const imports = LOCALES.flatMap((lang) =>
  NAMESPACES.map((ns) => `import ${ident(lang, ns)} from './${lang}/${ns}.json';`),
).join('\n');

const index = `// GENERATED by scripts/split-dictionaries.mjs. Do not edit by hand.
// Copy lives in ./ja/*.json and ./en/*.json (one file per owning package, spec §11).
${imports}

export const ja = ${composition('ja')};

/** The full dictionary shape. Japanese is the reference locale. */
export type Dictionary = typeof ja;

const enSource = ${composition('en')};

// Compile-time key parity: en must match ja exactly (no missing, no extra keys).
type Same<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false;
const parity: Same<typeof enSource, Dictionary> = true;
void parity;

export const en: Dictionary = enSource;
`;
emit(join(OUT, 'index.ts'), index);

if (CHECK && stale) {
  console.error(`${stale} generated dictionary file(s) differ from assets-src. Run npm run dict:split.`);
  process.exit(1);
}
